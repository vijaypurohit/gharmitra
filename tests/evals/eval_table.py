"""Builds reports/eval_table.md from collected eval results (scenario · expected · actual · pass/fail · notes)."""

from __future__ import annotations

import re
from pathlib import Path

TABLE = Path(__file__).resolve().parents[2] / "reports" / "eval_table.md"
ICON = {"passed": "✅ pass", "failed": "❌ fail", "error": "❌ error", "skipped": "⏭ skipped"}


def _cell(text: str) -> str:
    return re.sub(r"\s+", " ", str(text)).replace("|", "\\|").strip()


def _order(eval_id: str) -> int:
    return int(eval_id[1:]) if eval_id[1:].isdigit() else 999


def write(rows: list[dict], path: Path = TABLE) -> Path:
    rows = sorted(rows, key=lambda r: _order(r["id"]))
    counts = {k: sum(1 for r in rows if r["outcome"] == k) for k in ICON}
    lines = [
        "# Eval results",
        "",
        "Generated by `uv run pytest` (tests/evals/conftest.py). Do not edit by hand.",
        "",
        f"**{counts['passed']} passed · {counts['failed'] + counts['error']} failed · {counts['skipped']} skipped** "
        f"of {len(rows)} scenarios. ✅ in *Req* marks the coverage the brief requires.",
        "",
        "| Scenario | Req | Expected | Actual | Result | Notes |",
        "|---|:-:|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['id']} {_cell(r['name'])} | {'✅' if r.get('required') else ''} | {_cell(r['expected'])} "
            f"| {_cell(r.get('actual', ''))} | {ICON[r['outcome']]} | {_cell(r.get('notes', ''))} |"
        )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path
